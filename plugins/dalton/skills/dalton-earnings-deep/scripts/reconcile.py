#!/usr/bin/env python3
"""
reconcile.py — Preview-vs-Actual reconciliation CLI for Dalton earnings deep review (PS.9).

Reads `predictions.json` (generated by `dalton-earnings-preview`) and actual results
(from `--actuals <json_file>`, `--actual id=value` repeatable CLI flags, or stdin),
evaluates each prediction (`对` / `错` / `部分`), enforces error-reason attribution
(`数据错` / `模型错` / `判断错` / `意外事件`) for non-exact hits, and outputs the
Markdown reconciliation table with columns:
  `我们的预期｜一致预期｜实际｜对/错/部分｜错因`

Usage:
  python3 reconcile.py --predictions predictions.json --actuals actuals.json --output reconcile.md
  python3 reconcile.py --predictions predictions.json --actual P1="40,850|对|" --actual P2="5.10|错|模型错：低估了新晶圆厂折旧爬坡"
"""

import argparse
import json
from pathlib import Path
import re
import sys


VALID_VERDICTS = ("对", "错", "部分")
ERROR_CATEGORIES = ("数据错", "模型错", "判断错", "意外事件")


def _parse_numbers(text: str) -> list[float]:
    if text is None:
        return []
    cleaned = str(text).replace(",", "")
    matches = re.findall(r"[-+]?\d+(?:\.\d+)?", cleaned)
    return [float(m) for m in matches]


def _auto_judge(our_exp: str, actual_str: str) -> tuple[str, str]:
    """Best-effort automatic verdict when explicit verdict is not supplied in actuals."""
    exp_s = str(our_exp or "").strip()
    act_s = str(actual_str or "").strip()
    if not act_s or act_s in ("未披露", "not disclosed", "N/A"):
        return "部分", "数据错：当期未披露对应口径实际值，待 10-Q 补充核对"

    nums_act = _parse_numbers(act_s)
    nums_exp = _parse_numbers(exp_s)

    # Range check: e.g. "40,500 - 41,200" or "40500至41200"
    if len(nums_exp) >= 2 and any(sep in exp_s for sep in ("-", "~", "至", "to", "–")) and len(nums_act) >= 1:
        low, high = min(nums_exp[0], nums_exp[1]), max(nums_exp[0], nums_exp[1])
        val = nums_act[0]
        if low <= val <= high:
            return "对", "—"
        # Within 2% of range boundary -> 部分
        span_ref = max(abs(low), abs(high), 1e-9)
        dist = (low - val) if val < low else (val - high)
        if dist / span_ref <= 0.02:
            return "部分", "模型错：实际值接近预测区间边界但略有偏离（请核实具体驱动）"
        return "错", "判断错：实际值显著偏离前瞻预测区间（请核实具体驱动）"

    # Directional check: "> 5.35", ">= 20%"
    if exp_s.startswith((">=", ">")) and nums_exp and nums_act:
        ok = nums_act[0] >= nums_exp[0] if exp_s.startswith(">=") else nums_act[0] > nums_exp[0]
        return ("对", "—") if ok else ("错", "判断错：实际值未达到前瞻设定的下限阈值")
    if exp_s.startswith(("<=", "<")) and nums_exp and nums_act:
        ok = nums_act[0] <= nums_exp[0] if exp_s.startswith("<=") else nums_act[0] < nums_exp[0]
        return ("对", "—") if ok else ("错", "判断错：实际值超出前瞻设定的上限阈值")

    # Point comparison (within 1.5% tolerance -> 对, within 4% -> 部分, else 错)
    if len(nums_exp) == 1 and len(nums_act) == 1:
        target_v, act_v = nums_exp[0], nums_act[0]
        denom = max(abs(target_v), 1e-9)
        rel_err = abs(act_v - target_v) / denom
        if rel_err <= 0.015:
            return "对", "—"
        if rel_err <= 0.04:
            return "部分", "模型错：方向一致但点预测幅度存在偏差"
        return "错", "判断错：点预测偏差超过 4%"

    # Exact substring or qualitative match
    if exp_s.lower() == act_s.lower():
        return "对", "—"
    return "部分", "判断错：需结合定性表述人工确认错因"


def _load_predictions(path: Path) -> tuple[dict, list[dict]]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(raw, list):
        return {}, raw
    if isinstance(raw, dict):
        preds = raw.get("predictions")
        if isinstance(preds, list):
            return raw, preds
    raise ValueError(f"Invalid predictions.json format in {path}")


def _load_actuals(args: argparse.Namespace) -> dict[str, dict]:
    """Load actuals mapping keyed by prediction `id` or `metric`."""
    mapping: dict[str, dict] = {}
    if args.actuals:
        raw = json.loads(Path(args.actuals).read_text(encoding="utf-8"))
        if isinstance(raw, dict) and "actuals" in raw and isinstance(raw["actuals"], (dict, list)):
            raw = raw["actuals"]
        if isinstance(raw, list):
            for item in raw:
                if isinstance(item, dict):
                    key = str(item.get("id") or item.get("metric") or "").strip()
                    if key:
                        mapping[key] = item
        elif isinstance(raw, dict):
            for k, v in raw.items():
                if isinstance(v, dict):
                    mapping[str(k).strip()] = v
                else:
                    mapping[str(k).strip()] = {"actual": str(v)}

    if args.actual:
        for spec in args.actual:
            if "=" not in spec:
                raise ValueError(f"Invalid --actual '{spec}', expected ID=ACTUAL or ID=ACTUAL|VERDICT|REASON")
            k, rest = spec.split("=", 1)
            parts = rest.split("|")
            entry: dict = {"actual": parts[0].strip()}
            if len(parts) >= 2 and parts[1].strip():
                entry["verdict"] = parts[1].strip()
            if len(parts) >= 3 and parts[2].strip():
                entry["error_reason"] = parts[2].strip()
            mapping[k.strip()] = entry

    return mapping


def reconcile_items(predictions: list[dict], actuals_map: dict[str, dict]) -> dict:
    rows: list[dict] = []
    lessons_candidates: list[dict] = []
    counts = {"对": 0, "部分": 0, "错": 0, "total": len(predictions)}

    for p in predictions:
        pid = str(p.get("id") or "").strip()
        metric = str(p.get("metric") or "").strip()
        period = str(p.get("period") or "").strip()
        basis = str(p.get("basis") or "").strip()
        our_exp = str(p.get("our_expectation") or "").strip()
        street = str(p.get("street") or "").strip()
        bogey = p.get("bogey")

        act_entry = actuals_map.get(pid) or actuals_map.get(metric) or {}
        actual_val = str(act_entry.get("actual") or act_entry.get("value") or "未提供").strip()
        verdict = str(act_entry.get("verdict") or act_entry.get("result") or "").strip()
        error_reason = str(act_entry.get("error_reason") or act_entry.get("reason") or "").strip()

        if verdict not in VALID_VERDICTS:
            auto_v, auto_r = _auto_judge(our_exp, actual_val)
            verdict = auto_v
            if not error_reason:
                error_reason = auto_r

        if verdict == "对":
            if not error_reason:
                error_reason = "—"
        else:
            if not error_reason or error_reason == "—":
                error_reason = "判断错：待补充具体错因（数据错/模型错/判断错/意外事件）"
            elif not any(cat in error_reason for cat in ERROR_CATEGORIES):
                error_reason = f"判断错：{error_reason}"

        counts[verdict] = counts.get(verdict, 0) + 1

        row = {
            "id": pid,
            "metric": metric,
            "period": period,
            "basis": basis,
            "our_expectation": our_exp,
            "street": street,
            "bogey": bogey,
            "actual": actual_val,
            "verdict": verdict,
            "error_reason": error_reason,
            "linked_debate": p.get("linked_debate"),
            "linked_pillar": p.get("linked_pillar"),
        }
        rows.append(row)

        if verdict in ("错", "部分"):
            root_cat = next((c for c in ERROR_CATEGORIES if c in error_reason), "判断错")
            lessons_candidates.append(
                {
                    "prediction_id": pid,
                    "metric": f"{metric} ({period})",
                    "verdict": verdict,
                    "error_category": root_cat,
                    "error_reason": error_reason,
                    "linked_debate": p.get("linked_debate"),
                    "linked_pillar": p.get("linked_pillar"),
                    "lesson_candidate": act_entry.get("lesson")
                    or f"在预测 {metric} ({period}) 时出现{root_cat}（预期 {our_exp} vs 实际 {actual_val}）：{error_reason}",
                }
            )

    return {
        "ok": True,
        "counts": counts,
        "rows": rows,
        "lessons_candidates": lessons_candidates,
    }


def render_markdown(meta: dict, result: dict) -> str:
    ticker = meta.get("ticker") or ""
    quarter = meta.get("quarter") or ""
    title_suffix = f"（{ticker} {quarter}）" if (ticker or quarter) else ""
    counts = result["counts"]

    lines = [
        f"### 前瞻对账{title_suffix}",
        "",
        f"对账汇总：共 **{counts['total']}** 项预测 —— **对 {counts['对']}** 项｜**部分 {counts['部分']}** 项｜**错 {counts['错']}** 项。",
        "表头口径：`我们的预期｜一致预期｜实际｜对/错/部分｜错因`",
        "",
        "| 指标（ID｜期间｜口径） | 我们的预期 | 一致预期 | 实际 | 对/错/部分 | 错因 |",
        "|---|---|---|---|---|---|",
    ]
    for r in result["rows"]:
        label = f"**{r['metric']}**（{r['id']}｜{r['period']}｜{r['basis']}）"
        our_col = r["our_expectation"].replace("|", "｜")
        street_col = r["street"].replace("|", "｜")
        act_col = f"**{r['actual']}**".replace("|", "｜")
        v_col = f"**{r['verdict']}**" if r["verdict"] != "对" else r["verdict"]
        err_col = r["error_reason"].replace("|", "｜")
        lines.append(f"| {label} | {our_col} | {street_col} | {act_col} | {v_col} | {err_col} |")

    if result["lessons_candidates"]:
        lines.extend(
            [
                "",
                "#### 错判归因与 Lessons 候选",
                "",
            ]
        )
        for lc in result["lessons_candidates"]:
            lines.append(
                f"- **[{lc['prediction_id']}] {lc['metric']}（{lc['verdict']}｜{lc['error_category']}）**："
                f"{lc['lesson_candidate']}（关联：{lc.get('linked_debate') or '-'} / {lc.get('linked_pillar') or '-'}）"
            )
    return "\n".join(lines) + "\n"


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Reconcile predictions.json against actual earnings results and output Markdown table (PS.9)."
    )
    p.add_argument("--predictions", "-p", required=True, help="Path to preview predictions.json")
    p.add_argument("--actuals", "-a", default=None, help="Path to actuals JSON file (dict or list keyed by id/metric)")
    p.add_argument(
        "--actual",
        action="append",
        default=None,
        help="Inline actual specification: ID=ACTUAL or ID=ACTUAL|对/错/部分|错因 (repeatable)",
    )
    p.add_argument("--output", "-o", default=None, help="Write Markdown output to file")
    p.add_argument("--json", action="store_true", help="Print JSON reconciliation payload to stdout")
    return p


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    pred_path = Path(args.predictions)
    if not pred_path.exists():
        err = {"ok": False, "error": f"predictions file not found: {pred_path}"}
        print(json.dumps(err, ensure_ascii=False, indent=2))
        return 1

    try:
        meta, preds = _load_predictions(pred_path)
        actuals_map = _load_actuals(args)
        result = reconcile_items(preds, actuals_map)
        md_text = render_markdown(meta, result)

        if args.output:
            out_path = Path(args.output)
            out_path.parent.mkdir(parents=True, exist_ok=True)
            out_path.write_text(md_text, encoding="utf-8")

        if args.json:
            payload = {
                "ok": True,
                "predictions_file": str(pred_path),
                "output_file": args.output,
                **result,
                "markdown": md_text,
            }
            print(json.dumps(payload, ensure_ascii=False, indent=2))
        else:
            print(md_text, end="")
        return 0
    except Exception as exc:
        print(json.dumps({"ok": False, "error": str(exc)}, ensure_ascii=False, indent=2))
        return 1


if __name__ == "__main__":
    sys.exit(main())
