#!/usr/bin/env python3
"""Read-only drift checker between versioned data assets and deployed var/ copy.

Compares ``scripts/dalton/data_assets/{scripts,skills}/`` against
``var/dalton/openclaw-data/{scripts,skills}/`` byte-for-byte (SHA-256),
ignoring ``__pycache__``, ``*.pyc``, ``*.pyo``, and ``.DS_Store``.

Prints four sorted sections:
- 一致 (matched)
- 漂移 (drifted)
- 只在仓库 (repo_only)
- 只在 var (var_only)

Exit codes:
- 0: all files match (no drifted, repo_only, or var_only entries)
- 1: any drift or one-sided difference detected
- 2: missing or unreadable check root directory

Strictly read-only: never creates, modifies, or deletes any files.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import sys
from typing import Sequence

DEFAULT_SUBDIRS: tuple[str, ...] = ("scripts", "skills")
IGNORED_DIR_NAMES: frozenset[str] = frozenset({"__pycache__"})
IGNORED_FILE_NAMES: frozenset[str] = frozenset({".DS_Store"})
IGNORED_FILE_SUFFIXES: tuple[str, ...] = (".pyc", ".pyo")

ANTIGRAVITY_SERIES_MODULE_REL = "skills/model-usage-cost/scripts/antigravity_series.py"
ANTIGRAVITY_SERIES_JSON_REL = "skills/model-usage-cost/references/antigravity_series.json"


@dataclass(frozen=True)
class DriftReport:
    """Comparison summary between repo data_assets and deployed var/ copy."""

    matched: tuple[str, ...]
    drifted: tuple[str, ...]
    repo_only: tuple[str, ...]
    var_only: tuple[str, ...]

    @property
    def has_drift(self) -> bool:
        return bool(self.drifted or self.repo_only or self.var_only)

    def to_dict(self) -> dict[str, object]:
        return {
            "ok": not self.has_drift,
            "matched": list(self.matched),
            "drifted": list(self.drifted),
            "repo_only": list(self.repo_only),
            "var_only": list(self.var_only),
            "counts": {
                "matched": len(self.matched),
                "drifted": len(self.drifted),
                "repo_only": len(self.repo_only),
                "var_only": len(self.var_only),
            },
        }


def _should_ignore_file(name: str) -> bool:
    if name in IGNORED_FILE_NAMES:
        return True
    return name.endswith(IGNORED_FILE_SUFFIXES)


def _validate_readable_dir(path: Path, label: str) -> None:
    if not path.exists():
        raise FileNotFoundError(f"{label} 目录不存在: {path}")
    if not path.is_dir():
        raise NotADirectoryError(f"{label} 不是目录: {path}")
    if not os.access(path, os.R_OK | os.X_OK):
        raise PermissionError(f"{label} 目录不可读: {path}")


def _collect_files(root: Path, subdirs: Sequence[str]) -> dict[str, Path]:
    files: dict[str, Path] = {}
    for subdir in subdirs:
        base = root / subdir
        if not base.exists():
            continue
        if not base.is_dir() or not os.access(base, os.R_OK | os.X_OK):
            raise PermissionError(f"检查子目录不可读: {base}")
        for dirpath, dirnames, filenames in os.walk(base, followlinks=False):
            dirnames[:] = sorted(d for d in dirnames if d not in IGNORED_DIR_NAMES)
            current = Path(dirpath)
            for fname in sorted(filenames):
                if _should_ignore_file(fname):
                    continue
                full = current / fname
                rel = full.relative_to(root).as_posix()
                files[rel] = full
    return files


def _bytes_signature(data: bytes) -> tuple[str, str]:
    return ("file", hashlib.sha256(data).hexdigest())


def _file_signature(path: Path) -> tuple[str, str]:
    if path.is_symlink():
        return ("symlink", os.readlink(path))
    h = hashlib.sha256()
    with path.open("rb") as fh:
        while True:
            chunk = fh.read(65536)
            if not chunk:
                break
            h.update(chunk)
    return ("file", h.hexdigest())


def _infer_repo_root(repo_dir: Path) -> Path | None:
    resolved = repo_dir.resolve()
    parts = resolved.parts
    if len(parts) >= 3 and parts[-3:] == ("scripts", "dalton", "data_assets"):
        candidate = resolved.parents[2]
        if (candidate / "src" / "dalton" / "llm" / "antigravity_series.py").is_file():
            return candidate
    return None


def _collect_seed_generated_signatures(
    repo_dir: Path,
    subdirs: Sequence[str],
    *,
    repo_root: Path | None = None,
) -> dict[str, tuple[str, str]]:
    """Compute in-memory expected signatures for files generated by seed_openclaw_data.sh.

    Strictly read-only: mirrors seed_openclaw_data.sh's Antigravity series module
    copy and JSON export when ``skills`` is compared against a repository tree that
    provides ``skills/model-usage-cost/scripts/usage_sources.py`` and
    ``src/dalton/llm/antigravity_series.py``.
    """
    if "skills" not in subdirs:
        return {}
    usage_sources_path = repo_dir / "skills" / "model-usage-cost" / "scripts" / "usage_sources.py"
    if not usage_sources_path.is_file():
        return {}
    root = repo_root or _infer_repo_root(repo_dir)
    if root is None:
        return {}
    ag_module_path = root / "src" / "dalton" / "llm" / "antigravity_series.py"
    if not ag_module_path.is_file():
        return {}

    expected: dict[str, tuple[str, str]] = {
        ANTIGRAVITY_SERIES_MODULE_REL: _file_signature(ag_module_path),
    }

    skill_scripts_dir = str(usage_sources_path.parent)
    added_sys_path = False
    if skill_scripts_dir not in sys.path:
        sys.path.insert(0, skill_scripts_dir)
        added_sys_path = True
    prev_dont_write_bytecode = sys.dont_write_bytecode
    sys.dont_write_bytecode = True
    try:
        us_spec = importlib.util.spec_from_file_location("_drift_usage_sources", usage_sources_path)
        ag_spec = importlib.util.spec_from_file_location("_drift_antigravity_series", ag_module_path)
        if us_spec is None or us_spec.loader is None or ag_spec is None or ag_spec.loader is None:
            return expected
        usage_mod = importlib.util.module_from_spec(us_spec)
        sys.modules["_drift_usage_sources"] = usage_mod
        us_spec.loader.exec_module(usage_mod)
        ag_mod = importlib.util.module_from_spec(ag_spec)
        sys.modules["_drift_antigravity_series"] = ag_mod
        ag_spec.loader.exec_module(ag_mod)

        series = usage_mod.build_antigravity_series_from_overlays(
            (
                root / "src" / "dalton" / "llm" / "native_overlay.json",
                root / "var" / "dalton" / "catalog" / "native_sync_overlay.json",
            ),
            dalton_yaml_path=root / "src" / "dalton" / "dalton.yaml",
            ag_mod=ag_mod,
        )
        rendered = (json.dumps(series, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
        expected[ANTIGRAVITY_SERIES_JSON_REL] = _bytes_signature(rendered)
    finally:
        sys.dont_write_bytecode = prev_dont_write_bytecode
        sys.modules.pop("_drift_usage_sources", None)
        sys.modules.pop("_drift_antigravity_series", None)
        if added_sys_path and skill_scripts_dir in sys.path:
            sys.path.remove(skill_scripts_dir)

    return expected


def compare_data_assets(
    repo_dir: Path,
    var_dir: Path,
    *,
    subdirs: Sequence[str] = DEFAULT_SUBDIRS,
    repo_root: Path | None = None,
) -> DriftReport:
    """Compare ``repo_dir/{subdirs}`` against ``var_dir/{subdirs}`` without writing."""
    _validate_readable_dir(repo_dir, "repo")
    _validate_readable_dir(var_dir, "var")

    repo_files = _collect_files(repo_dir, subdirs)
    var_files = _collect_files(var_dir, subdirs)

    repo_sigs: dict[str, tuple[str, str]] = {
        rel: _file_signature(path) for rel, path in repo_files.items()
    }
    generated_sigs = _collect_seed_generated_signatures(
        repo_dir,
        subdirs,
        repo_root=repo_root,
    )
    for rel, sig in generated_sigs.items():
        repo_sigs.setdefault(rel, sig)

    repo_keys = set(repo_sigs)
    var_keys = set(var_files)

    matched: list[str] = []
    drifted: list[str] = []
    for rel in sorted(repo_keys & var_keys):
        if repo_sigs[rel] == _file_signature(var_files[rel]):
            matched.append(rel)
        else:
            drifted.append(rel)

    repo_only = sorted(repo_keys - var_keys)
    var_only = sorted(var_keys - repo_keys)

    return DriftReport(
        matched=tuple(matched),
        drifted=tuple(drifted),
        repo_only=tuple(repo_only),
        var_only=tuple(var_only),
    )


def format_report(report: DriftReport, repo_dir: Path, var_dir: Path) -> str:
    lines: list[str] = [
        f"Data assets drift check (read-only)",
        f"  repo: {repo_dir}",
        f"  var:  {var_dir}",
    ]
    sections: tuple[tuple[str, tuple[str, ...]], ...] = (
        ("一致", report.matched),
        ("漂移", report.drifted),
        ("只在仓库", report.repo_only),
        ("只在 var", report.var_only),
    )
    for label, items in sections:
        lines.append(f"\n{label} ({len(items)}):")
        if not items:
            lines.append("  (无)")
        else:
            for item in items:
                lines.append(f"  - {item}")
    return "\n".join(lines)


def _default_repo_root() -> Path:
    # scripts/dalton/ops/prod/check_data_assets_drift.py -> parents[4] is repo root
    return Path(__file__).resolve().parents[4]


def main(argv: Sequence[str] | None = None) -> int:
    sys.dont_write_bytecode = True
    repo_root = _default_repo_root()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--repo-dir",
        type=Path,
        default=repo_root / "scripts" / "dalton" / "data_assets",
        help="Versioned data_assets directory (default: <repo>/scripts/dalton/data_assets)",
    )
    parser.add_argument(
        "--var-dir",
        type=Path,
        default=repo_root / "var" / "dalton" / "openclaw-data",
        help="Deployed var data directory (default: <repo>/var/dalton/openclaw-data)",
    )
    parser.add_argument(
        "--subdirs",
        default=",".join(DEFAULT_SUBDIRS),
        help="Comma-separated subdirectories to compare (default: scripts,skills)",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="Emit machine-readable JSON output",
    )
    args = parser.parse_args(argv)

    subdirs = tuple(part.strip() for part in args.subdirs.split(",") if part.strip())
    try:
        report = compare_data_assets(args.repo_dir, args.var_dir, subdirs=subdirs)
    except (FileNotFoundError, NotADirectoryError, PermissionError, OSError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    if args.json:
        print(json.dumps(report.to_dict(), ensure_ascii=False, indent=2))
    else:
        print(format_report(report, args.repo_dir, args.var_dir))

    return 1 if report.has_drift else 0


if __name__ == "__main__":
    sys.exit(main())
