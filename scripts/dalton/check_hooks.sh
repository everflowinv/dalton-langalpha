is_allowed() {
  local needle="$1"
  for id in "${ALLOWED_HOOKS[@]}"; do
    if [[ "$id" == "$needle" ]]; then
      return 0
    fi
  done
  return 1
}

# Compute upstream merge-base (P0F.2: always compare against upstream/main merge-base or 8e0dce94)
if git rev-parse -q --verify MERGE_HEAD >/dev/null 2>&1; then
  MERGE_BASE="$(git merge-base MERGE_HEAD upstream/main 2>/dev/null || git rev-parse MERGE_HEAD)"
else
  MERGE_BASE="$(git merge-base HEAD upstream/main 2>/dev/null || echo 8e0dce94)"
fi
if [[ "$STRICT" -eq 1 ]]; then
  BASE_REF="$MERGE_BASE"
else
  BASE_REF="${DALTON_BASE_REF:-$MERGE_BASE}"
fi

PYTHON_CMD=(".venv/bin/python")
if [[ ! -x ".venv/bin/python" ]]; then
  PYTHON_CMD=("uv" "run" "--no-sync" "python")
fi

if [[ "$AUDIT" -eq 1 ]]; then
  "${PYTHON_CMD[@]}" - "$BASE_REF" <<'PY'
import pathlib, re, subprocess, sys

base_ref = sys.argv[1]
repo = pathlib.Path.cwd()
paths_file = repo / "scripts" / "dalton" / "dalton_paths.txt"
dalton_prefixes = [
    line.strip()
    for line in paths_file.read_text(encoding="utf-8").splitlines()
    if line.strip() and not line.strip().startswith("#")
]

# Exempt pure lock/locale/test-contract files that do not use inline DALTON-HOOK comments
AUDIT_EXEMPT_FILES = {
    # The fork replaces the whole README (marked once at its top, DALTON-HOOK(docs-readme)),
    # so every edit is Dalton's and a per-hunk marker would only be noise.
    "README.md",
    "tests/unit/mcp_servers/agent_docstring_lock.json",
    "tests/unit/mcp_servers/test_agent_contract.py",
    "tests/unit/mcp_servers/test_entrypoint_imports.py",
    "tests/unit/middleware/skills/test_shared_skill_layer.py",
    "web/src/components/nav/__tests__/useNavItems.test.tsx",
    "web/src/locales/en-US.json",
    "web/src/locales/zh-CN.json",
    # Generated by scripts/utils/export_market_data_tools.py from the hooked
    # price_data_mcp_server.py (extended_hours); JSON carries no inline markers.
    "mcp_servers/contract/market_data.tools.json",
}

def is_dalton_owned(rel: str) -> bool:
    for p in dalton_prefixes:
        if rel == p or rel.startswith(p):
            return True
    return False

out = subprocess.check_output(
    ["git", "diff", "--name-status", base_ref], text=True
).splitlines()

new_in_upstream = []
unhooked_edits = []
hooked_edits = []

for row in out:
    if not row.strip():
        continue
    parts = row.split("\t")
    status = parts[0]
    rel = parts[-1]
    if is_dalton_owned(rel) or rel in AUDIT_EXEMPT_FILES:
        continue
    if status.startswith("A"):
        new_in_upstream.append(rel)
        continue
    if status.startswith("M"):
        file_path = repo / rel
        if not file_path.exists():
            continue
        lines = file_path.read_text(encoding="utf-8", errors="replace").splitlines()
        diff_text = subprocess.check_output(
            ["git", "diff", "-U0", base_ref, "--", rel], text=True
        )
        hunk_starts = []
        for dline in diff_text.splitlines():
            m = re.match(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@", dline)
            if m:
                start = int(m.group(1))
                count = int(m.group(2) or "1")
                if count > 0:
                    hunk_starts.append((start, start + count - 1))
        file_unhooked = []
        for s, e in hunk_starts:
            win_s = max(1, s - 25)
            win_e = min(len(lines), e + 25)
            window = "\n".join(lines[win_s - 1 : win_e])
            if "DALTON-HOOK" not in window:
                file_unhooked.append(f"L{s}-L{e}")
        if file_unhooked:
            unhooked_edits.append((rel, file_unhooked))
        else:
            hooked_edits.append(rel)

print(f"=== DALTON HOOK AUDIT (base={base_ref[:10]}) ===")
print(f"NEW_IN_UPSTREAM_DIR ({len(new_in_upstream)}):")
for f in new_in_upstream:
    print(f"  NEW_IN_UPSTREAM_DIR: {f}")
print(f"UNHOOKED_EDIT ({len(unhooked_edits)}):")
for f, ranges in unhooked_edits:
    print(f"  UNHOOKED_EDIT: {f} ({', '.join(ranges)})")
print(f"HOOKED_EDIT ({len(hooked_edits)}):")
for f in hooked_edits:
    print(f"  HOOKED_EDIT: {f}")
if new_in_upstream or unhooked_edits:
    sys.exit(2)
PY
  AUDIT_RC=$?
  if [[ "$STRICT" -eq 0 ]]; then
    exit 0
  elif [[ "$AUDIT_RC" -ne 0 ]]; then
    echo "ERROR (--strict --audit): Found NEW_IN_UPSTREAM_DIR or UNHOOKED_EDIT" >&2
    exit 1
  fi
fi

# Find all DALTON-HOOK(<id>) or DALTON-HOOK: markers outside docs/dalton and scripts/dalton/check_hooks.sh
MATCHES="$(git grep -n "DALTON-HOOK(" -- ':!docs/dalton/**' ':!scripts/dalton/check_hooks.sh' || true)"

echo "=== Registered DALTON-HOOK occurrences ==="
if [[ -z "$MATCHES" ]]; then
  echo "(none yet)"
else
  echo "$MATCHES"
fi

ERRORS=0
FOUND_IDS=()

while IFS= read -r line; do
  [[ -z "$line" ]] && continue
  if [[ "$line" =~ DALTON-HOOK\(([a-z0-9-]+)\) ]]; then
    hook_id="${BASH_REMATCH[1]}"
    FOUND_IDS+=("$hook_id")
    if ! is_allowed "$hook_id"; then
      echo "ERROR: Unregistered DALTON-HOOK($hook_id) found: $line" >&2
      ERRORS=$((ERRORS + 1))
    fi
  else
    echo "ERROR: Malformed DALTON-HOOK marker (expected DALTON-HOOK(<id>)): $line" >&2
    ERRORS=$((ERRORS + 1))
  fi
done <<< "$MATCHES"

if [[ "$STRICT" -eq 1 ]]; then
  for req in "${P0_REQUIRED_HOOKS[@]}"; do
    found=0
    for f in "${FOUND_IDS[@]:-}"; do
      if [[ "$f" == "$req" ]]; then
        found=1
        break
      fi
    done
    if [[ "$found" -eq 0 ]]; then
      echo "ERROR (--strict): Required P0 hook DALTON-HOOK($req) is missing" >&2
      ERRORS=$((ERRORS + 1))
    fi
  done
fi

# Verify protected upstream config files are untouched vs base ref
if git rev-parse --verify "$BASE_REF" >/dev/null 2>&1; then
  UNTOUCHED_FILES=("src/llms/manifest/models.json" "src/llms/manifest/providers.json" "agent_config.yaml" "config.yaml")
  for uf in "${UNTOUCHED_FILES[@]}"; do
    if ! git diff --quiet "$BASE_REF" -- "$uf"; then
      echo "ERROR: Upstream file $uf was modified relative to $BASE_REF (must use overlay instead)" >&2
      ERRORS=$((ERRORS + 1))
    fi
  done

  # P0F.2 #3: Verify agent_docstring_lock.json is additive-only vs BASE_REF (except pinned sha256 hook keys) and only adds dalton_* keys
  if ! "${PYTHON_CMD[@]}" - "$BASE_REF" <<'PY'
import hashlib, json, subprocess, sys
base_ref = sys.argv[1]
base_json = json.loads(subprocess.check_output(["git", "show", f"{base_ref}:tests/unit/mcp_servers/agent_docstring_lock.json"], text=True))
cur_json = json.loads(open("tests/unit/mcp_servers/agent_docstring_lock.json", encoding="utf-8").read())
pinned_modified_sha256 = {
    "direct:get_daily_prices": "8ac5caef9f4daf0aaeba4243dd3523871fe4d1b5887004580b510a7d5c026098",
    "direct:get_quote": "3048022c2ebe1b63286a638dcfb09da38f4510fb24b3006b840c8a1a54ca93cd",
    "mcp:price_data:get_asset_data": "ddaeb61647241627897cbf68ae19a28bd8ed3b015e0060e7649421b6fbb75372",
    "mcp:price_data:get_stock_data": "1207da227ebdfcfd4d706e737fec94345e54cb7cdd32f21c3087e0dfa53336e8",
    "mcp:yf_price:get_multiple_stocks_history": "f7c61b74abe894ccbe723329e971a2e2ea27d8c735ae6ddb490b4ea6c33f12ad",
    "mcp:yf_price:get_stock_history": "bc8586db7b45021313669c22a045a3a554403fa5a334056772aef8c8e09ca0ad",
}
errors = []
for k, expected_sha in pinned_modified_sha256.items():
    if k not in cur_json:
        errors.append(f"Missing pinned key {k} from agent_docstring_lock.json")
    else:
        cur_sha = hashlib.sha256(
            json.dumps(cur_json[k], sort_keys=True, ensure_ascii=False).encode("utf-8")
        ).hexdigest()
        if cur_sha != expected_sha:
            errors.append(
                f"Pinned key {k} in agent_docstring_lock.json has sha256={cur_sha}, "
                f"expected {expected_sha}"
            )
for k, v in base_json.items():
    if k in pinned_modified_sha256:
        continue
    if k not in cur_json:
        errors.append(f"Removed upstream key {k} from agent_docstring_lock.json")
    elif cur_json[k] != v:
        errors.append(f"Modified upstream key {k} in agent_docstring_lock.json")
for k in cur_json:
    if k not in base_json and not (k.startswith("dalton_") or k.startswith("mcp:dalton_")):
        errors.append(f"Added non-dalton key {k} to agent_docstring_lock.json")
if errors:
    for e in errors:
        print("ERROR:", e, file=sys.stderr)
    sys.exit(1)
PY
  then
    ERRORS=$((ERRORS + 1))
  fi
fi

if [[ "$ERRORS" -gt 0 ]]; then
  echo "FAILED: $ERRORS hook check error(s)." >&2
  exit 1
fi

echo "OK: DALTON-HOOK check passed."
