def _fallback_atomic_write_json_locked(
    path: Path, payload: dict[str, Any], *, label: str = "state"
) -> bool:
    """Fallback atomic writer used only when `researchdata_bridge._atomic_write_json_locked` is not passed."""
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        lock_path = path.with_name(f"{path.name}.lock")
        tmp_path = path.with_name(
            f".{path.name}.{os.getpid()}.{uuid.uuid4().hex[:8]}.tmp"
        )
        with lock_path.open("a+", encoding="utf-8") as lock_fh:
            fcntl.flock(lock_fh.fileno(), fcntl.LOCK_EX)
            try:
                tmp_path.write_text(
                    json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8",
                )
                os.replace(tmp_path, path)
            finally:
                try:
                    if tmp_path.exists():
                        tmp_path.unlink()
                except Exception:
                    pass
                fcntl.flock(lock_fh.fileno(), fcntl.LOCK_UN)
        return True
    except Exception as exc:
        logger.warning("Failed writing %s file: %s", label, type(exc).__name__)
        return False


