class AsrJobManager:
    """Manages on-disk ASR job state under ``<DALTON_ASR_JOBS_DIR>/<job_id>/``."""

    def __init__(
        self,
        jobs_dir: Path,
        *,
        worker: AsrWorkerProtocol,
        atomic_write_fn: Callable[..., bool] | None = None,
        usage_ledger_path: Path | None = None,
        owner_lock: AsrOwnerLock | None = None,
        auto_recover: bool = True,
    ) -> None:
        if owner_lock is not None and not owner_lock.is_held:
            raise RuntimeError(
                "AsrOwnerLock must be acquired before constructing AsrJobManager"
            )
        self.owner_lock = owner_lock
        self.jobs_dir = Path(jobs_dir).expanduser()
        env_usage = os.environ.get("DALTON_ASR_USAGE_FILE", "").strip()
        self.usage_ledger_path = (
            Path(env_usage).expanduser()
            if usage_ledger_path is None and env_usage
            else (
                Path(usage_ledger_path).expanduser()
                if usage_ledger_path is not None
                else self.jobs_dir / "asr_usage.jsonl"
            )
        )
        self._atomic_write = atomic_write_fn or atomic_write_json_locked
        self.worker: AsrWorkerProtocol = worker
        self._tasks: dict[str, asyncio.Task[None]] = {}
        self._locks: dict[str, asyncio.Lock] = {}
        self._exec_locks: dict[str, asyncio.Lock] = {}
        self._explicit_cancels: set[str] = set()
        self._recovered_on_startup: bool = False
        if auto_recover:
            try:
                asyncio.get_running_loop()
                self.recover_incomplete_jobs()
            except RuntimeError:
                pass

    def active_job_ids(self) -> list[str]:
        """Return sorted IDs of jobs currently executing in background tasks."""
        return sorted(
            jid for jid, task in self._tasks.items() if task is not None and not task.done()
        )

    async def shutdown(self, *, grace_s: float = 5.0) -> None:
        """Wait briefly for in-flight tasks, then cancel remaining tasks cleanly.

        Cancellation during shutdown does NOT mark jobs ``cancelled``; non-terminal
        jobs are persisted with ``interrupted: True`` so the next lock owner resumes them.
        """
        running = [t for t in self._tasks.values() if t is not None and not t.done()]
        if not running:
            return
        if grace_s > 0:
            done, pending = await asyncio.wait(running, timeout=float(grace_s))
            _ = done
            running = list(pending)
        if running:
            for task in running:
                if not task.done():
                    task.cancel()
            await asyncio.gather(*running, return_exceptions=True)

    def recover_incomplete_jobs(self) -> list[str]:
        """Scan ``jobs_dir`` and resume any non-terminal jobs interrupted by a prior process exit."""
        self._recovered_on_startup = True
        resumed: list[str] = []
        if not self.jobs_dir.is_dir():
            return resumed
        try:
            for entry in sorted(self.jobs_dir.iterdir()):
                if not entry.is_dir():
                    continue
                job_id = entry.name
                if not _SAFE_JOB_ID_RE.fullmatch(job_id):
                    continue
                state = self.read_state(job_id)
                if not isinstance(state, dict):
                    continue
                if state.get("status") in RECOVERABLE_JOB_STATUSES:
                    self._ensure_worker_running(job_id)
                    resumed.append(job_id)
        except Exception as exc:
            logger.warning(
                "Failed scanning ASR jobs directory for recovery: %s",
                type(exc).__name__,
            )
        return resumed

    def _ensure_recovered(self) -> None:
        if not self._recovered_on_startup:
            self.recover_incomplete_jobs()

    def _job_lock(self, job_id: str) -> asyncio.Lock:
        lock = self._locks.get(job_id)
        if lock is None:
            lock = asyncio.Lock()
            self._locks[job_id] = lock
        return lock

    def _exec_lock(self, job_id: str) -> asyncio.Lock:
        lock = self._exec_locks.get(job_id)
        if lock is None:
            lock = asyncio.Lock()
            self._exec_locks[job_id] = lock
        return lock

    def _resolve_job_dir(self, job_id: str) -> Path | None:
        cleaned = str(job_id or "").strip()
        if not _SAFE_JOB_ID_RE.fullmatch(cleaned):
            return None
        base = self.jobs_dir.resolve()
        candidate = (base / cleaned).resolve()
        if not candidate.is_relative_to(base) or candidate == base:
            return None
        return candidate

    def state_path(self, job_id: str) -> Path | None:
        job_dir = self._resolve_job_dir(job_id)
        return (job_dir / "state.json") if job_dir is not None else None

    def result_path(self, job_id: str) -> Path | None:
        job_dir = self._resolve_job_dir(job_id)
        return (job_dir / "result.json") if job_dir is not None else None

    def raw_response_path(self, job_id: str) -> Path | None:
        job_dir = self._resolve_job_dir(job_id)
        return (job_dir / "raw_response.json") if job_dir is not None else None

    def read_state(self, job_id: str) -> dict[str, Any] | None:
        spath = self.state_path(job_id)
        if spath is None or not spath.is_file():
            return None
        try:
            raw = json.loads(spath.read_text(encoding="utf-8"))
            return raw if isinstance(raw, dict) else None
        except Exception as exc:
            logger.warning("Failed reading ASR job state for %s: %s", job_id, type(exc).__name__)
            return None

    def read_result(self, job_id: str) -> dict[str, Any] | None:
        rpath = self.result_path(job_id)
        if rpath is None or not rpath.is_file():
            return None
        try:
            raw = json.loads(rpath.read_text(encoding="utf-8"))
            return raw if isinstance(raw, dict) else None
        except Exception as exc:
            logger.warning("Failed reading ASR job result for %s: %s", job_id, type(exc).__name__)
            return None

    def _write_state(self, job_id: str, state: dict[str, Any]) -> bool:
        spath = self.state_path(job_id)
        if spath is None:
            return False
        try:
            return bool(self._atomic_write(spath, state, label="asr_job_state"))
        except Exception as exc:
            logger.warning("Failed writing ASR job state for %s: %s", job_id, type(exc).__name__)
            return False

    def _write_result(self, job_id: str, result: dict[str, Any]) -> bool:
        rpath = self.result_path(job_id)
        if rpath is None:
            return False
        try:
            return bool(self._atomic_write(rpath, result, label="asr_job_result"))
        except Exception as exc:
            logger.warning("Failed writing ASR job result for %s: %s", job_id, type(exc).__name__)
            return False

    def _write_raw_response(self, job_id: str, raw_bundle: dict[str, Any]) -> bool:
        raw_path = self.raw_response_path(job_id)
        if raw_path is None:
            return False
        return bool(self._atomic_write(raw_path, raw_bundle, label="asr_raw_response"))

    def _ensure_worker_running(self, job_id: str) -> None:
        existing = self._tasks.get(job_id)
        if existing is not None and not existing.done():
            return
        task = asyncio.create_task(self._execute_job(job_id))
        self._tasks[job_id] = task

    async def _execute_job(self, job_id: str) -> None:
        async with self._exec_lock(job_id):
            state = self.read_state(job_id)
            if state is None:
                return
            if state.get("status") in TERMINAL_JOB_STATUSES:
                return
            run_attempt = int(state.get("attempt") or 1)

            async def _on_progress(patch: dict[str, Any]) -> bool:
                async with self._job_lock(job_id):
                    cur = self.read_state(job_id)
                    if (
                        cur is None
                        or cur.get("status") == "cancelled"
                        or int(cur.get("attempt") or 1) != run_attempt
                    ):
                        return False
                    cur.pop("interrupted", None)
                    cur.pop("interrupted_at", None)
                    cur.update(patch)
                    cur["version"] = int(cur.get("version") or 1) + 1
                    cur["updated_at"] = _now_iso()
                    return self._write_state(job_id, cur)

            try:
                outcome = await self.worker.run_job(state, on_progress=_on_progress)
            except asyncio.CancelledError:
                if job_id in self._explicit_cancels:
                    cleanup_fn = getattr(self.worker, "cleanup_job_resources", None)
                    if callable(cleanup_fn):
                        cur_for_clean = self.read_state(job_id) or state
                        segs_for_clean = [
                            s
                            for s in (cur_for_clean.get("segments") or [])
                            if isinstance(s, dict)
                        ]
                        try:
                            await _maybe_await(cleanup_fn(job_id, segs_for_clean))
                        except Exception:
                            pass
                else:
                    async with self._job_lock(job_id):
                        cur = self.read_state(job_id)
                        if (
                            cur is not None
                            and cur.get("status") not in TERMINAL_JOB_STATUSES
                            and int(cur.get("attempt") or 1) == run_attempt
                        ):
                            now_str = _now_iso()
                            cur["interrupted"] = True
                            cur["interrupted_at"] = now_str
                            cur["version"] = int(cur.get("version") or 1) + 1
                            cur["updated_at"] = now_str
                            self._write_state(job_id, cur)
                raise
            except Exception as exc:
                logger.warning("ASR worker failed for job_id=%s: %s", job_id, type(exc).__name__)
                cleanup_fn = getattr(self.worker, "cleanup_job_resources", None)
                if callable(cleanup_fn):
                    cur_for_clean = self.read_state(job_id) or state
                    segs_for_clean = [
                        s
                        for s in (cur_for_clean.get("segments") or [])
                        if isinstance(s, dict)
                    ]
                    try:
                        await _maybe_await(cleanup_fn(job_id, segs_for_clean))
                    except Exception:
                        pass
                outcome = {
                    "status": "failed",
                    "stage": "failed",
                    "error_category": "worker_exception",
                    "error_message": f"{type(exc).__name__}: {redact_asr_secrets(str(exc))}",
                }

            async with self._job_lock(job_id):
                cur = self.read_state(job_id)
                if (
                    cur is None
                    or cur.get("status") == "cancelled"
                    or int(cur.get("attempt") or 1) != run_attempt
                ):
                    return
                cur.pop("interrupted", None)
                cur.pop("interrupted_at", None)
                result_payload = outcome.pop("result", None)
                if isinstance(result_payload, dict):
                    self._write_result(job_id, result_payload)
                raw_response_payload = outcome.pop("raw_response", None)
                if isinstance(raw_response_payload, dict):
                    self._write_raw_response(job_id, raw_response_payload)

                prev_usage = (
                    dict(cur.get("usage")) if isinstance(cur.get("usage"), dict) else {}
                )
                prev_attempts = [
                    dict(a)
                    for a in (prev_usage.get("attempts") or [])
                    if isinstance(a, dict)
                ]
                cur.update(outcome)
                cur["version"] = int(cur.get("version") or 1) + 1
                now_str = _now_iso()
                cur["updated_at"] = now_str
                if cur.get("status") in TERMINAL_JOB_STATUSES:
                    cur["completed_at"] = now_str

                cur_status_str = str(cur.get("status") or "")
                if cur_status_str in ("succeeded", "failed"):
                    existing_att_rec = next(
                        (
                            a
                            for a in prev_attempts
                            if int(a.get("attempt") or 0) == run_attempt
                            and str(a.get("status") or "").strip()
                            in ("succeeded", "failed", "cancelled")
                        ),
                        None,
                    )
                    attempt_record = (
                        existing_att_rec
                        if existing_att_rec is not None
                        else build_attempt_usage_record(
                            cur,
                            attempt=run_attempt,
                            status=cur_status_str,
                            recorded_at=now_str,
                        )
                    )
                    dedup_attempts: list[dict[str, Any]] = [
                        a
                        for a in prev_attempts
                        if int(a.get("attempt") or 0) != run_attempt
                    ]
                    dedup_attempts.append(attempt_record)
                    dedup_attempts.sort(key=lambda a: int(a.get("attempt") or 0))
                    usage_dict = (
                        dict(cur.get("usage")) if isinstance(cur.get("usage"), dict) else {}
                    )
                    caller_obj = (
                        cur.get("caller") if isinstance(cur.get("caller"), dict) else {}
                    )
                    usage_dict["user_id"] = str(
                        caller_obj.get("user_id") or usage_dict.get("user_id") or ""
                    )
                    usage_dict["workspace_id"] = str(
                        caller_obj.get("workspace_id") or usage_dict.get("workspace_id") or ""
                    )
                    usage_dict["thread_id"] = str(
                        caller_obj.get("thread_id") or usage_dict.get("thread_id") or ""
                    )
                    usage_dict["attempt"] = run_attempt
                    usage_dict["status"] = str(attempt_record.get("status") or cur_status_str)
                    usage_dict["ok"] = bool(attempt_record.get("ok"))
                    usage_dict["segment_count"] = int(cur.get("segment_count") or 0)
                    usage_dict["completed_segments"] = int(cur.get("completed_segments") or 0)
                    usage_dict["error_category"] = attempt_record.get("error_category")
                    usage_dict["attempts"] = dedup_attempts
                    cur["usage"] = usage_dict

                    recorded_list = [
                        int(x)
                        for x in (cur.get("usage_recorded_attempts") or [])
                        if isinstance(x, int) and not isinstance(x, bool)
                    ]
                    if run_attempt not in recorded_list:
                        append_usage_jsonl(self.usage_ledger_path, attempt_record)
                        recorded_list.append(run_attempt)
                        cur["usage_recorded_attempts"] = sorted(set(recorded_list))

                self._write_state(job_id, cur)

    async def submit_job(self, body: dict[str, Any]) -> tuple[int, dict[str, Any]]:
        """Validate and enqueue a transcription job."""
        if not isinstance(body, dict):
            return 400, {
                "ok": False,
                "error_code": "invalid_body",
                "error": "Expected JSON object",
            }

        job_id = str(body.get("job_id") or "").strip()
        if not _SAFE_JOB_ID_RE.fullmatch(job_id):
            return 400, {
                "ok": False,
                "error_code": "invalid_job_id",
                "error": "job_id is required and must be a safe identifier",
            }

        caller_raw = body.get("caller")
        if not isinstance(caller_raw, dict):
            return 400, {
                "ok": False,
                "error_code": "missing_caller",
                "error": "caller object (user_id, workspace_id, thread_id) is required",
            }
        user_id = str(caller_raw.get("user_id") or "").strip()
        workspace_id = str(caller_raw.get("workspace_id") or "").strip()
        thread_id = str(caller_raw.get("thread_id") or "").strip()
        if not user_id or not workspace_id:
            return 400, {
                "ok": False,
                "error_code": "missing_caller_identity",
                "error": "caller.user_id and caller.workspace_id are required",
            }

        source_object_key = str(body.get("source_object_key") or "").strip()
        if (
            not source_object_key
            or "://" in source_object_key
            or source_object_key.startswith("/")
            or ".." in source_object_key.split("/")
            or _FORBIDDEN_KEY_CHARS_RE.search(source_object_key)
            or not source_object_key.startswith(
                (f"transcriptions/{workspace_id}/", f"uploads/{workspace_id}/")
            )
        ):
            return 400, {
                "ok": False,
                "error_code": "invalid_source_object_key",
                "error": "source_object_key must be a valid workspace-scoped object key",
            }

        size_raw = body.get("source_size_bytes")
        if not isinstance(size_raw, int) or isinstance(size_raw, bool) or size_raw <= 0:
            return 400, {
                "ok": False,
                "error_code": "invalid_source_size",
                "error": "source_size_bytes must be a positive integer",
            }

        sha_raw = str(body.get("source_sha256") or "").strip().lower()
        if not _SHA256_RE.fullmatch(sha_raw):
            return 400, {
                "ok": False,
                "error_code": "invalid_source_sha256",
                "error": "source_sha256 must be a 64-character hex digest",
            }

        idemp_key = str(body.get("idempotency_key") or "").strip()
        if not idemp_key:
            return 400, {
                "ok": False,
                "error_code": "missing_idempotency_key",
                "error": "idempotency_key is required",
            }

        language = (
            str(body.get("language")).strip()
            if body.get("language") is not None and str(body.get("language")).strip()
            else None
        )
        hotwords_raw = body.get("hotwords")
        hotwords = (
            [str(w).strip() for w in hotwords_raw if str(w).strip()]
            if isinstance(hotwords_raw, list)
            else []
        )

        async with self._job_lock(job_id):
            existing = self.read_state(job_id)
            if existing is not None:
                ex_caller = existing.get("caller") or {}
                if (
                    ex_caller.get("user_id") != user_id
                    or ex_caller.get("workspace_id") != workspace_id
                ):
                    return 409, {
                        "ok": False,
                        "error_code": "job_id_conflict",
                        "error": "job_id already exists for a different caller or workspace",
                    }
                if existing.get("status") in ACTIVE_JOB_STATUSES:
                    self._ensure_worker_running(job_id)
                return 200, {"ok": True, "job": existing}

            now_str = _now_iso()
            state: dict[str, Any] = {
                "job_id": job_id,
                "status": "queued",
                "stage": "queued",
                "version": 1,
                "attempt": 1,
                "caller": {
                    "user_id": user_id,
                    "workspace_id": workspace_id,
                    "thread_id": thread_id,
                },
                "source_object_key": source_object_key,
                "source_size_bytes": int(size_raw),
                "source_sha256": sha_raw,
                "language": language,
                "hotwords": hotwords,
                "idempotency_key": idemp_key,
                "segment_count": 1,
                "completed_segments": 0,
                "current_segment": None,
                "segments": [],
                "provider_request_ids": [],
                "usage": {
                    "user_id": user_id,
                    "workspace_id": workspace_id,
                    "thread_id": thread_id,
                    "duration_seconds": 0.0,
                    "submitted_seconds": 0.0,
                    "completed_seconds": 0.0,
                    "billable_seconds": None,
                },
                "result_object_key": None,
                "error_category": None,
                "error_message": None,
                "created_at": now_str,
                "updated_at": now_str,
                "completed_at": None,
            }
            if not self._write_state(job_id, state):
                return 500, {
                    "ok": False,
                    "error_code": "state_write_failed",
                    "error": "Failed persisting ASR job state to disk",
                }
            self._ensure_worker_running(job_id)
            return 200, {"ok": True, "job": state}

    async def get_job(self, job_id: str) -> tuple[int, dict[str, Any]]:
        """Read job state from disk, resuming if interrupted."""
        self._ensure_recovered()
        state = self.read_state(job_id)
        if state is None:
            return 404, {
                "ok": False,
                "error_code": "not_found",
                "error": "Transcription job not found",
            }
        if state.get("status") in ACTIVE_JOB_STATUSES:
            self._ensure_worker_running(job_id)
        return 200, {"ok": True, "job": state}

    async def get_job_result(self, job_id: str) -> tuple[int, dict[str, Any]]:
        """Read transcription result JSON from disk."""
        self._ensure_recovered()
        state = self.read_state(job_id)
        if state is None:
            return 404, {
                "ok": False,
                "error_code": "not_found",
                "error": "Transcription job not found",
            }
        cur_status = str(state.get("status") or "")
        if cur_status != "succeeded":
            return 409, {
                "ok": False,
                "error_code": "not_ready",
                "status": cur_status,
                "error": f"Transcription result is not ready (status={cur_status})",
            }
        result = self.read_result(job_id)
        if result is None:
            return 404, {
                "ok": False,
                "error_code": "result_missing",
                "error": "Transcription result file is missing",
            }
        return 200, {
            "ok": True,
            "job_id": job_id,
            "status": "succeeded",
            "caller": state.get("caller") or {},
            "usage": state.get("usage") or {},
            "result_object_key": state.get("result_object_key"),
            "result": result,
        }

    async def get_job_raw_result(
        self, job_id: str
    ) -> tuple[int, dict[str, Any] | Path]:
        """Resolve raw provider response file (``raw_response.json``) for streaming."""
        self._ensure_recovered()
        state = self.read_state(job_id)
        if state is None:
            return 404, {
                "ok": False,
                "error_code": "not_found",
                "error": "Transcription job not found",
            }
        cur_status = str(state.get("status") or "")
        if cur_status != "succeeded":
            return 409, {
                "ok": False,
                "error_code": "not_ready",
                "status": cur_status,
                "error": f"Transcription result is not ready (status={cur_status})",
            }
        raw_path = self.raw_response_path(job_id)
        if raw_path is None or not raw_path.is_file():
            return 404, {
                "ok": False,
                "error_code": "raw_response_missing",
                "error": "Raw provider response file is not available",
            }
        return 200, raw_path

    async def retry_job(
        self, job_id: str, body: dict[str, Any] | None = None
    ) -> tuple[int, dict[str, Any]]:
        """Retry a ``failed`` or ``indeterminate`` job (idempotent when already active)."""
        async with self._job_lock(job_id):
            state = self.read_state(job_id)
            if state is None:
                return 404, {
                    "ok": False,
                    "error_code": "not_found",
                    "error": "Transcription job not found",
                }
            cur_status = str(state.get("status") or "")
            if cur_status in ACTIVE_JOB_STATUSES and int(state.get("attempt") or 1) > 1:
                self._ensure_worker_running(job_id)
                return 200, {"ok": True, "job": state, "deduplicated": True}

            if cur_status not in ("failed", "indeterminate"):
                return 409, {
                    "ok": False,
                    "error_code": "invalid_state",
                    "status": cur_status,
                    "error": f"Job in status '{cur_status}' cannot be retried",
                }
            segs = state.get("segments")
            already_done = (
                sum(
                    1
                    for s in segs
                    if isinstance(s, dict) and s.get("status") == "succeeded"
                )
                if isinstance(segs, list)
                else 0
            )
            self._explicit_cancels.discard(job_id)
            state.pop("interrupted", None)
            state.pop("interrupted_at", None)
            state["status"] = "queued"
            state["stage"] = "queued"
            state["attempt"] = int(state.get("attempt") or 1) + 1
            state["version"] = int(state.get("version") or 1) + 1
            state["completed_segments"] = already_done
            state["current_segment"] = None
            state["error_category"] = None
            state["error_message"] = None
            state["updated_at"] = _now_iso()
            state["completed_at"] = None
            if not self._write_state(job_id, state):
                return 500, {
                    "ok": False,
                    "error_code": "state_write_failed",
                    "error": "Failed persisting retried ASR job state",
                }
            self._ensure_worker_running(job_id)
            return 200, {"ok": True, "job": state}

    async def cancel_job(
        self, job_id: str, body: dict[str, Any] | None = None
    ) -> tuple[int, dict[str, Any]]:
        """Cancel an in-flight or queued job and clean up temporary files."""
        segments_to_clean: list[dict[str, Any]] = []
        async with self._job_lock(job_id):
            state = self.read_state(job_id)
            if state is None:
                return 404, {
                    "ok": False,
                    "error_code": "not_found",
                    "error": "Transcription job not found",
                }
            cur_status = str(state.get("status") or "")
            if cur_status == "succeeded":
                return 409, {
                    "ok": False,
                    "error_code": "already_succeeded",
                    "status": cur_status,
                    "error": "Succeeded transcription job cannot be cancelled",
                }
            if cur_status == "cancelled":
                return 200, {"ok": True, "job": state}

            self._explicit_cancels.add(job_id)
            running_task = self._tasks.pop(job_id, None)
            if running_task is not None and not running_task.done():
                running_task.cancel()

            raw_segs = state.get("segments")
            submitted_req_ids: list[str] = []
            all_provider_req_ids: list[str] = []
            unsubmitted_cancelled_count = 0
            completed_segments_count = 0
            seg_submitted_seconds = 0.0
            seg_completed_seconds = 0.0
            if isinstance(raw_segs, list):
                for s in raw_segs:
                    if not isinstance(s, dict):
                        continue
                    segments_to_clean.append(s)
                    seg_st = str(s.get("status") or "")
                    req_id = str(s.get("provider_request_id") or "").strip()
                    seg_dur = max(
                        0.0,
                        float(s.get("end_s") or 0.0) - float(s.get("start_s") or 0.0),
                    )
                    if req_id:
                        if req_id not in all_provider_req_ids:
                            all_provider_req_ids.append(req_id)
                        seg_submitted_seconds += seg_dur
                    if seg_st == "succeeded":
                        completed_segments_count += 1
                        seg_completed_seconds += seg_dur
                    elif req_id:
                        if req_id not in submitted_req_ids:
                            submitted_req_ids.append(req_id)
                        s["provider_cancel_verified"] = False
                    else:
                        s["status"] = "cancelled"
                        unsubmitted_cancelled_count += 1
            for req_id_raw in state.get("provider_request_ids") or []:
                req_id_s = str(req_id_raw or "").strip()
                if req_id_s:
                    if req_id_s not in all_provider_req_ids:
                        all_provider_req_ids.append(req_id_s)
                    if not isinstance(raw_segs, list) and req_id_s not in submitted_req_ids:
                        submitted_req_ids.append(req_id_s)

            now_str = _now_iso()
            cancellation_info = {
                "cancelled_at": now_str,
                "submitted_segments_count": len(submitted_req_ids),
                "submitted_request_ids": list(submitted_req_ids),
                "unsubmitted_cancelled_count": unsubmitted_cancelled_count,
                "completed_segments_count": completed_segments_count,
                "provider_cancel_verified": False,
                "billing_verified": False,
                "notice": PROVIDER_CANCEL_UNVERIFIED_NOTICE,
            }
            prev_usage = (
                dict(state.get("usage")) if isinstance(state.get("usage"), dict) else {}
            )
            prev_attempts = [
                dict(a)
                for a in (prev_usage.get("attempts") or [])
                if isinstance(a, dict)
            ]
            run_attempt = int(state.get("attempt") or 1)
            existing_attempt_rec = next(
                (
                    a
                    for a in prev_attempts
                    if int(a.get("attempt") or 0) == run_attempt
                    and str(a.get("status") or "").strip()
                    in ("succeeded", "failed", "cancelled")
                ),
                None,
            )
            if existing_attempt_rec is None and cur_status in ("succeeded", "failed"):
                existing_attempt_rec = build_attempt_usage_record(
                    state,
                    attempt=run_attempt,
                    status=cur_status,
                    recorded_at=str(
                        state.get("completed_at")
                        or state.get("updated_at")
                        or state.get("created_at")
                        or now_str
                    ),
                )
                if all_provider_req_ids:
                    existing_attempt_rec["provider_request_ids"] = list(all_provider_req_ids)
                prev_attempts.append(existing_attempt_rec)
                prev_attempts.sort(key=lambda a: int(a.get("attempt") or 0))

            state.pop("interrupted", None)
            state.pop("interrupted_at", None)
            state["status"] = "cancelled"
            state["stage"] = "cancelled"
            state["version"] = int(state.get("version") or 1) + 1
            state["current_segment"] = None
            state["cancellation"] = cancellation_info
            if all_provider_req_ids:
                state["provider_request_ids"] = list(all_provider_req_ids)
            usage_dict = dict(prev_usage)
            if (
                seg_submitted_seconds > 0.0
                and float(usage_dict.get("submitted_seconds") or 0.0) <= 0.0
            ):
                usage_dict["submitted_seconds"] = round(seg_submitted_seconds, 3)
            if (
                seg_completed_seconds > 0.0
                and float(usage_dict.get("completed_seconds") or 0.0) <= 0.0
            ):
                usage_dict["completed_seconds"] = round(seg_completed_seconds, 3)
            usage_dict["cancellation"] = dict(cancellation_info)
            if prev_attempts:
                usage_dict["attempts"] = prev_attempts
            state["usage"] = usage_dict
            state["updated_at"] = now_str
            state["completed_at"] = state.get("completed_at") or now_str

            recorded_list = [
                int(x)
                for x in (state.get("usage_recorded_attempts") or [])
                if isinstance(x, int) and not isinstance(x, bool)
            ]
            if existing_attempt_rec is not None:
                usage_dict["status"] = str(existing_attempt_rec.get("status") or cur_status)
                usage_dict["ok"] = bool(existing_attempt_rec.get("ok"))
                state["usage"] = usage_dict
                if run_attempt not in recorded_list:
                    append_usage_jsonl(self.usage_ledger_path, existing_attempt_rec)
                    recorded_list.append(run_attempt)
                    state["usage_recorded_attempts"] = sorted(set(recorded_list))
            else:
                has_submitted_segments = bool(
                    all_provider_req_ids
                    or submitted_req_ids
                    or completed_segments_count > 0
                    or float(usage_dict.get("submitted_seconds") or 0.0) > 0.0
                )
                if has_submitted_segments:
                    attempt_record = build_attempt_usage_record(
                        state,
                        attempt=run_attempt,
                        status="cancelled",
                        recorded_at=now_str,
                    )
                    attempt_record["provider_request_ids"] = list(all_provider_req_ids)
                    attempt_record["billing_verified"] = False
                    dedup_attempts: list[dict[str, Any]] = [
                        a
                        for a in prev_attempts
                        if int(a.get("attempt") or 0) != run_attempt
                    ]
                    dedup_attempts.append(attempt_record)
                    dedup_attempts.sort(key=lambda a: int(a.get("attempt") or 0))
                    caller_obj = (
                        state.get("caller") if isinstance(state.get("caller"), dict) else {}
                    )
                    usage_dict["user_id"] = str(
                        caller_obj.get("user_id") or usage_dict.get("user_id") or ""
                    )
                    usage_dict["workspace_id"] = str(
                        caller_obj.get("workspace_id") or usage_dict.get("workspace_id") or ""
                    )
                    usage_dict["thread_id"] = str(
                        caller_obj.get("thread_id") or usage_dict.get("thread_id") or ""
                    )
                    usage_dict["attempt"] = run_attempt
                    usage_dict["status"] = "cancelled"
                    usage_dict["ok"] = False
                    usage_dict["billing_verified"] = False
                    usage_dict["attempts"] = dedup_attempts
                    state["usage"] = usage_dict

                    if run_attempt not in recorded_list:
                        append_usage_jsonl(self.usage_ledger_path, attempt_record)
                        recorded_list.append(run_attempt)
                        state["usage_recorded_attempts"] = sorted(set(recorded_list))

            if not self._write_state(job_id, state):
                return 500, {
                    "ok": False,
                    "error_code": "state_write_failed",
                    "error": "Failed persisting cancelled ASR job state",
                }

        cleanup_fn = getattr(self.worker, "cleanup_job_resources", None)
        if callable(cleanup_fn):
            try:
                await _maybe_await(cleanup_fn(job_id, segments_to_clean))
            except Exception as exc:
                logger.warning(
                    "Cancel cleanup warning for job_id=%s: %s", job_id, type(exc).__name__
                )
        return 200, {
            "ok": True,
            "job": state,
            "cancellation": state.get("cancellation"),
        }

    def read_usage_ledger(self) -> list[dict[str, Any]]:
        """Read deduplicated per-attempt usage records from ``self.usage_ledger_path``."""
        return read_usage_jsonl(self.usage_ledger_path)


