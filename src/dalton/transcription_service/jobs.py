"""Open-source disk-backed ASR job manager and usage JSONL ledger.

Maintains exact on-disk layout compatibility with legacy ``scripts/dalton/asr_jobs.py``:
- ``<DALTON_ASR_JOBS_DIR>/<job_id>/state.json``
- ``<DALTON_ASR_JOBS_DIR>/<job_id>/result.json``
- ``<DALTON_ASR_JOBS_DIR>/<job_id>/raw_response.json``
- ``<DALTON_ASR_JOBS_DIR>/<job_id>/transcript.txt``
- ``<DALTON_ASR_JOBS_DIR>/asr_usage.jsonl`` (or ``DALTON_ASR_USAGE_FILE``)

Jobs created by the legacy bridge before cutover can be queried, downloaded,
retried, cancelled, recovered, and billed seamlessly by ``dalton-transcription``
(and vice versa on rollback).
"""

